#!/usr/bin/env python3
"""
Deterministic Python `decimal.Decimal` (prec=60, ROUND_HALF_UP) Compliance Vector
Generator for ImpulseVM v0.11.0 DECIMAL64 instructions:
  - 0x15 OP_SCALAR_DECIMAL_ALU (16 subops: 0..15)
  - 0x58 OP_VEC_DECIMAL_ALU    (16 subops: 0..15)
  - 0x52 OP_VEC_REDUCE         (subop 11: sum_i64_chk)
  - 0x37 OP_MORSEL_COMMIT      (subop 9:  scatter_add_chk)

Generates positive and negative `.impas` compliance vectors directly into:
  - test-vectors/vm-impas/01_pillar1_control_scalar/p1_dec_*.impas
  - test-vectors/vm-impas/03_pillar3_walks_morsels_kernels/p3_dec_*.impas
  - test-vectors/vm-impas/04_pillar4_vectors_math_keys/p4_dec_*.impas
"""

from __future__ import annotations

import json
import math
import struct
from decimal import Context, Decimal, ROUND_CEILING, ROUND_DOWN, ROUND_FLOOR, ROUND_HALF_UP
from pathlib import Path

SPEC_ROOT = Path(__file__).resolve().parent.parent
P1_DIR = SPEC_ROOT / "test-vectors" / "vm-impas" / "01_pillar1_control_scalar"
P3_DIR = SPEC_ROOT / "test-vectors" / "vm-impas" / "03_pillar3_walks_morsels_kernels"
P4_DIR = SPEC_ROOT / "test-vectors" / "vm-impas" / "04_pillar4_vectors_math_keys"

INT64_MIN = -(1 << 63)
INT64_MAX = (1 << 63) - 1

CTX = Context(prec=60, rounding=ROUND_HALF_UP)


def dec_round_half_up_div(num: int, den: int) -> int:
    assert den != 0
    q = CTX.divide(Decimal(num), Decimal(den))
    r = int(q.quantize(Decimal("1"), rounding=ROUND_HALF_UP))
    assert INT64_MIN <= r <= INT64_MAX, f"Unexpected overflow: {r}"
    return r


def dec_mul_div_round(a: int, b: int, d: int) -> int:
    assert d != 0
    prod = CTX.multiply(Decimal(a), Decimal(b))
    q = CTX.divide(prod, Decimal(d))
    r = int(q.quantize(Decimal("1"), rounding=ROUND_HALF_UP))
    assert INT64_MIN <= r <= INT64_MAX, f"Unexpected overflow: {r}"
    return r


def dec_trunc_scale(a: int, s: int) -> int:
    q = CTX.divide(Decimal(a), Decimal(10**s))
    return int(q.quantize(Decimal("1"), rounding=ROUND_DOWN))


def dec_floor_scale(a: int, s: int) -> int:
    q = CTX.divide(Decimal(a), Decimal(10**s))
    return int(q.quantize(Decimal("1"), rounding=ROUND_FLOOR))


def dec_ceil_scale(a: int, s: int) -> int:
    q = CTX.divide(Decimal(a), Decimal(10**s))
    return int(q.quantize(Decimal("1"), rounding=ROUND_CEILING))


def dec_f64_to_dec(x: float, scale: int, prec: int) -> int:
    assert math.isfinite(x)
    scaled = x * (10.0**scale)
    # Match half-away-from-zero on IEEE-754 f64
    r = int(Decimal(scaled).quantize(Decimal("1"), rounding=ROUND_HALF_UP))
    lim = 10**prec - 1
    assert abs(r) <= lim
    return r


def i64_hex(v: int) -> str:
    return f"0x{v & 0xFFFFFFFFFFFFFFFF:016X}"


def f64_hex(v: float) -> str:
    bits = struct.unpack("<Q", struct.pack("<d", v))[0]
    return f"0x{bits:016X}"


def write_vec(directory: Path, name: str, content: str) -> Path:
    path = directory / name
    path.write_text(content.lstrip("\n"), encoding="utf-8")
    return path


